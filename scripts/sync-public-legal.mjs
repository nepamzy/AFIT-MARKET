// Copies the published legal texts in docs/legal/*.md into src/content/legal-public.generated.ts (shown at /legal).
// Run after editing a text:  node scripts/sync-public-legal.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const DOCS = [
  ['terms', 'Customer terms and conditions'],
  ['privacy', 'Privacy policy'],
  ['reports', 'Reports, returns and cancelled orders policy'],
  ['payments', 'Payments, delivery fee and payouts'],
  ['vendor-agreement', 'Vendor agreement'],
  ['rider-agreement', 'Rider agreement'],
  ['acceptable-use', 'Acceptable use and safety rules'],
]
const docs = DOCS.map(([slug, title]) => {
  const markdown = readFileSync(`docs/legal/${slug}.md`, 'utf8')
  const updated = /^Last updated:\s*(.+)$/m.exec(markdown)?.[1] ?? ''
  return { slug, title, updated, markdown }
})
writeFileSync(
  'src/content/legal-public.generated.ts',
  `// GENERATED by scripts/sync-public-legal.mjs from docs/legal. Do not edit by hand.\nexport const LEGAL_PUBLIC: { slug: string; title: string; updated: string; markdown: string }[] = ${JSON.stringify(docs, null, 2)}\n`,
)
console.log(`${docs.length} legal texts written`)
